"""Documentation generation from the static project index."""

from __future__ import annotations

from pathlib import Path

from .openapi import operations
from .scanner import ProjectIndex


def render_readme(index: ProjectIndex, project_name: str | None = None) -> str:
    name = project_name or index.root.name
    languages = ", ".join(index.technology.get("languages", [])) or "unknown"
    frameworks = ", ".join(index.technology.get("frameworks", [])) or "none detected"
    top_level = sorted(
        path.name
        for path in index.root.iterdir()
        if path.is_dir() and not path.name.startswith(".")
    )
    modules = "\n".join(f"- `{module}`" for module in sorted(index.modules)[:20])
    entrypoints = "\n".join(f"- `{entry}`" for entry in index.entrypoints[:10]) or "- none"
    return f"""# {name}

{name} is a {languages} project{f" using {frameworks}" if frameworks != "none detected" else ""}.

## Layout
{chr(10).join(f"- `{name}`" for name in top_level)}

## Entrypoints
{entrypoints}

## Modules
{modules}

## Development
- Test: `python -m pytest -q`
- Lint: `ruff check .`

Generated by the software engineering agent from static analysis. Review before publishing.
"""


def render_architecture(index: ProjectIndex) -> str:
    lines = ["# Architecture", "", "```mermaid", "graph TD"]
    names = sorted(index.modules)
    allowed = set(names[:24])
    aliases = {name: f"m{position}" for position, name in enumerate(sorted(allowed))}
    for name in sorted(allowed):
        lines.append(f'  {aliases[name]}["{name}"]')
    for name in sorted(allowed):
        for dependency in index.dependencies.get(name, []):
            if dependency in allowed:
                lines.append(f"  {aliases[dependency]} --> {aliases[name]}")
    if len(names) > len(allowed):
        lines.append(f'  rest["{len(names) - len(allowed)} more modules"]')
    lines.extend(["```", "", "Edges point from an imported module to its consumer."])
    return "\n".join(lines) + "\n"


def render_api_docs(spec: dict) -> str:
    lines = ["# API", "", "| Method | Path | Operation |", "|---|---|---|"]
    for operation in operations(spec):
        lines.append(
            f"| {operation.method.upper()} | `{operation.path}` | `{operation.operation_id}` |"
        )
    return "\n".join(lines) + "\n"


def missing_docstrings(index: ProjectIndex) -> list[str]:
    missing = []
    for module in index.modules.values():
        for function in module.functions:
            if not function.docstring and function.name != "__init__":
                missing.append(f"{module.name}:{function.line} {function.name}")
    return missing


def write_docs(index: ProjectIndex, output: Path, spec: dict | None = None) -> list[Path]:
    output.mkdir(parents=True, exist_ok=True)
    written = []
    readme = output / "README.generated.md"
    readme.write_text(render_readme(index), encoding="utf-8")
    written.append(readme)
    architecture = output / "ARCHITECTURE.md"
    architecture.write_text(render_architecture(index), encoding="utf-8")
    written.append(architecture)
    if spec is not None:
        api = output / "API.md"
        api.write_text(render_api_docs(spec), encoding="utf-8")
        written.append(api)
    return written
